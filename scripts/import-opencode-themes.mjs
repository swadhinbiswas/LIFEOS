/**
 * Import OpenCode's built-in themes as LifeOS presets (spec §4.2).
 *
 * Source of truth: the theme JSON files embedded in OpenCode
 * `packages/tui/src/theme/assets/*.json` (the list behind https://opencode.ai/docs/themes/).
 * The colours are read, never guessed; anything the source omits is derived from the theme's own
 * foreground/background mix and documented in the output.
 *
 * Because LifeOS enforces WCAG AA on every token pair (themes.test.ts), a palette that is
 * authentic but low-contrast is **adjusted by shifting its lightness away from the background**
 * until it passes — the original hex is kept in a comment, exactly as ADR-033 requires for the
 * hand-written presets.
 *
 * Idempotent: a marker in the generated section means re-running replaces it rather than
 * duplicating. Run with `node scripts/import-opencode-themes.mjs`.
 */
