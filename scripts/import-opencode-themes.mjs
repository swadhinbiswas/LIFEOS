// ---------------------------------------------------------------- color helpers
const parseHex = (raw) => {
  if (typeof raw !== "string" || !raw.startsWith("#")) return null;
  let h = raw.slice(1);
  if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join("");
  if (h.length !== 6 && h.length !== 8) return null;
  return {
    r: parseInt(h.slice(0, 2), 16),
    g: parseInt(h.slice(2, 4), 16),
    b: parseInt(h.slice(4, 6), 16),
    a: h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1,
  };
};
const toHex = ({ r, g, b }) =>
  `#${[r, g, b]
    .map((v) =>
      Math.round(Math.min(255, Math.max(0, v)))
        .toString(16)
        .padStart(2, "0"),
    )
    .join("")}`;
const over = (fg, bg) => ({
  r: fg.r * fg.a + bg.r * (1 - fg.a),
  g: fg.g * fg.a + bg.g * (1 - fg.a),
  b: fg.b * fg.a + bg.b * (1 - fg.a),
  a: 1,
});
const mix = (a, b, weight) =>
  toHex({
    r: a.r * weight + b.r * (1 - weight),
    g: a.g * weight + b.g * (1 - weight),
    b: a.b * weight + b.b * (1 - weight),
  });
const luminance = ({ r, g, b }) => {
  const [lr, lg, lb] = [r, g, b].map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * lr + 0.7152 * lg + 0.0722 * lb;
};
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const rgbToHsl = ({ r, g, b }) => {
  const [rn, gn, bn] = [r / 255, g / 255, b / 255];
  const max = Math.max(rn, gn, bn),
    min = Math.min(rn, gn, bn),
    d = max - min;
  const l = (max + min) / 2;
  let h = 0,
    s = 0;
  if (d !== 0) {
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === rn) h = ((gn - bn) / d + (gn < bn ? 6 : 0)) / 6;
    else if (max === gn) h = ((bn - rn) / d + 2) / 6;
    else h = ((rn - gn) / d + 4) / 6;
  }
  return { h, s, l };
};
const hslToRgb = ({ h, s, l }) => {
  if (s === 0) return { r: l * 255, g: l * 255, b: l * 255 };
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s;
  const p = 2 * l - q;
  const hue = (t) => {
    let x = t;
    if (x < 0) x += 1;
    if (x > 1) x -= 1;
    if (x < 1 / 6) return p + (q - p) * 6 * x;
    if (x < 1 / 2) return q;
    if (x < 2 / 3) return p + (q - p) * (2 / 3 - x) * 6;
    return p;
  };
  return { r: hue(h + 1 / 3) * 255, g: hue(h) * 255, b: hue(h - 1 / 3) * 255 };
};

/**
 * Shift lightness until the colour clears `min` against every background, keeping the hue.
 * `against` is the full set to pass; `reference` decides the direction (always the base surfaces,
 * so a lighter derived fill never flips a dark theme's correction to "darken").
 */
function ensureContrast(hex, against, min, reference = against) {
  const parsed = parseHex(hex);
  if (!parsed) return { hex, changed: false };
  const passes = (candidate) => {
    const p = parseHex(candidate);
    return p && against.every((bg) => contrast(p, bg) >= min);
  };
  if (passes(hex)) return { hex, changed: false };
  const { h, s, l } = rgbToHsl(parsed);
  const backgroundsAreDark = reference.every((bg) => luminance(bg) < 0.5);
  for (let step = 1; step <= 100; step += 1) {
    const next = backgroundsAreDark
      ? hslToRgb({ h, s, l: Math.min(1, l + step / 100) })
      : hslToRgb({ h, s, l: Math.max(0, l - step / 100) });
    const candidate = toHex(next);
    if (passes(candidate)) return { hex: candidate, changed: true };
  }
  return { hex: backgroundsAreDark ? "#ffffff" : "#000000", changed: true };
}

// ---------------------------------------------------------------- theme reading
const fetchTheme = async (name) => {
  const response = await fetch(`${RAW}/${name}.json`);
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  return response.json();
};

const resolve = (value, defs, mode, seen = new Set()) => {
  if (value == null) return null;
  if (typeof value === "object" && !Array.isArray(value)) {
    return resolve(value[mode] ?? value.dark ?? value.light, defs, mode, seen);
  }
  const direct = parseHex(value);
  if (direct) return direct;
  if (typeof value === "string" && defs[value] && !seen.has(value)) {
    seen.add(value);
    return resolve(defs[value], defs, mode, seen);
  }
  return null;
};

const presets = [];
const adjustments = [];

for (const name of NAMES) {
  const theme = await fetchTheme(name);
  const defs = theme.defs ?? {};
  const darkBg = resolve(theme.theme?.background, defs, "dark");
  const mode = !darkBg || luminance(darkBg) < 0.5 ? "dark" : "light";
  const at = (key) => resolve(theme.theme?.[key], defs, mode);

  // `transparent` themes (lucent-orng) keep the terminal's background; LifeOS needs a real one.
  const transparent = at("background") === null;
  const background =
    at("background") ??
    (mode === "dark" ? { r: 0x0a, g: 0x0a, b: 0x0a, a: 1 } : { r: 0xff, g: 0xff, b: 0xff, a: 1 });
  const card =
    at("backgroundPanel") ?? over(background, at("text") ?? { r: 0xff, g: 0xff, b: 0xff, a: 0.05 });
  const foreground =
    at("text") ??
    (mode === "dark" ? { r: 0xff, g: 0xff, b: 0xff, a: 1 } : { r: 0, g: 0, b: 0, a: 1 });
  const base = {
    background: toHex(background),
    card: toHex(card),
    foreground: toHex(foreground),
  };
  const bgs = [base.background, base.card].map((h) => parseHex(h));

  const originals = new Map();
  // `resolve()` returns {r,g,b,a}; flatten to a solid hex over the theme's own background first.
  const solid = (color) => (color ? toHex(over({ ...color, a: color.a ?? 1 }, bgs[0])) : null);
  const fix = (key, color, min = 4.5, against = bgs) => {
    const start = solid(color) ?? mix(parseHex(base.foreground), parseHex(base.background), 0.5);
    const result = ensureContrast(start, against, min, bgs);
    if (result.changed) originals.set(key, start);
    return result.hex;
  };

  const foregroundHex = fix("foreground", foreground, 4.5);
  // themes.test.ts also checks text against the derived fills (muted 8%, secondary 5%, accent-ui
  // 7% foreground over background), which sit *closer* to the foreground than the background does —
  // so text has to clear those too, not just the two surfaces.
  const textBgs = [
    ...bgs,
    ...[0.93, 0.95, 0.92].map((weight) =>
      parseHex(mix(parseHex(foregroundHex), parseHex(base.background), weight)),
    ),
  ];
  const fixText = (key, color) => fix(key, color, 4.5, textBgs);

  const accentRaw = at("accent") ?? at("primary") ?? foreground;
  const borderRaw = at("border");
  let border = solid(borderRaw) ?? mix(parseHex(base.foreground), parseHex(base.background), 0.18);
  // themes.test.ts checks `input = color-mix(border 50%, foreground)`, so adjust the border, not the mix.
  for (let step = 0; step <= 100; step += 1) {
    const probe = parseHex(mix(parseHex(border), parseHex(base.foreground), 0.5));
    if (bgs.every((bg) => contrast(probe, bg) >= 3)) break;
    const { h, s, l } = rgbToHsl(parseHex(border));
    const next = toHex(
      hslToRgb(
        bgs.every((bg) => luminance(bg) < 0.5)
          ? { h, s, l: Math.min(1, l + (step + 1) / 100) }
          : { h, s, l: Math.max(0, l - (step + 1) / 100) },
      ),
    );
    border = next;
  }
  const borderFixed = ensureContrast(border, bgs, 3);
  if (borderFixed.changed) originals.set("border", border);
  border = borderFixed.hex;

  const palette = {
    id: `oc-${name}`,
    label: LABELS[name] ?? name,
    nativeMode: mode,
    background: base.background,
    card: base.card,
    border,
    foreground: foregroundHex,
    mutedForeground: fixText("mutedForeground", at("textMuted")),
    primary: fixText("primary", at("primary")),
    success: fixText("success", at("success") ?? at("primary")),
    warning: fixText("warning", at("warning") ?? at("accent") ?? at("primary")),
    danger: fixText("danger", at("error") ?? { r: 0xd6, g: 0x4d, b: 0x4d, a: 1 }),
    info: fixText("info", at("info") ?? at("primary")),
    accent: fix("accent", accentRaw, 3),
  };

  presets.push(palette);
  adjustments.push({ name, originals, transparent });
}

// ---------------------------------------------------------------- emit
const tsLines = presets.map((preset) => {
  const notes = [...adjustments.find((a) => a.name === preset.id.slice(3)).originals.entries()]
    .map(([key, value]) => `    // OpenCode ${key} ${value} → adjusted for WCAG AA (ADR-033)`)
    .join("\n");
  const transparentNote = adjustments.find((a) => a.name === preset.id.slice(3))?.transparent
    ? "    // OpenCode background is 'transparent' (terminal default) → a solid base (ADR-094)"
    : "";
  const body = [
    `  "${preset.id}": {`,
    `    id: "${preset.id}",`,
    `    label: ${JSON.stringify(preset.label)},`,
    `    nativeMode: "${preset.nativeMode}",`,
    ...(transparentNote ? [transparentNote] : []),
    ...(notes ? [notes] : []),
    `    background: "${preset.background}",`,
    `    card: "${preset.card}",`,
    `    border: "${preset.border}",`,
    `    foreground: "${preset.foreground}",`,
    `    mutedForeground: "${preset.mutedForeground}",`,
    `    primary: "${preset.primary}",`,
    `    success: "${preset.success}",`,
    `    warning: "${preset.warning}",`,
    `    danger: "${preset.danger}",`,
    `    info: "${preset.info}",`,
    `    accent: "${preset.accent}",`,
    "  },",
  ];
  return body.join("\n");
});

