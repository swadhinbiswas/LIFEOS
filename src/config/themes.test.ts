/**
 * Automated WCAG AA contrast test for every theme token pair (spec §4.2 line 95).
 *
 * Thresholds: 4.5:1 for body-text pairs, 3:1 for UI/focus pairs (accent = focus ring
 * role, chart = data-viz). Divider `--border` has no WCAG threshold of its own — the
 * control boundary is --input, asserted at 3:1 (rationale in ADR-033).
 */
import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

import { contrastRatio, suggestNudge } from "@/lib/color";
import {
  accentCssVars,
  DEFAULT_THEME,
  derivedTokens,
  themes,
  THEME_PRESET_IDS,
  type ThemeOverrides,
  type ThemePreset,
} from "@/config/themes";

const TEXT_MIN = 4.5;
const UI_MIN = 3;

function check(label: string, fg: string, bg: string, min: number): void {
  const ratio = contrastRatio(fg, bg);
  expect(
    ratio,
    `${label}: ${fg} on ${bg} = ${ratio.toFixed(2)}:1 (need ≥${min}); ` +
      `try ${suggestNudge(fg, bg, min)}`,
  ).toBeGreaterThanOrEqual(min);
}

describe("theme contrast (spec §4.2)", () => {
  for (const id of THEME_PRESET_IDS) {
    const theme: ThemePreset = themes[id];
    const derived = derivedTokens(theme);
    const backgrounds: Array<[string, string]> = [
      ["background", theme.background],
      ["card", theme.card],
    ];

    describe(id, () => {
      for (const [bgName, bg] of backgrounds) {
        it(`body text ≥ 4.5:1 on ${bgName}`, () => {
          check(`${id} foreground×${bgName}`, theme.foreground, bg, TEXT_MIN);
          check(`${id} muted-foreground×${bgName}`, theme.mutedForeground, bg, TEXT_MIN);
          check(`${id} primary×${bgName}`, theme.primary, bg, TEXT_MIN);
          check(`${id} success×${bgName}`, theme.success, bg, TEXT_MIN);
          check(`${id} warning×${bgName}`, theme.warning, bg, TEXT_MIN);
          check(`${id} danger×${bgName}`, theme.danger, bg, TEXT_MIN);
          check(`${id} info×${bgName}`, theme.info, bg, TEXT_MIN);
          check(`${id} fg×muted-fill×${bgName}`, theme.foreground, derived.mutedFill, TEXT_MIN);
          check(
            `${id} muted-fg×muted-fill×${bgName}`,
            theme.mutedForeground,
            derived.mutedFill,
            TEXT_MIN,
          );
          check(
            `${id} fg×secondary-fill×${bgName}`,
            theme.foreground,
            derived.secondaryFill,
            TEXT_MIN,
          );
          check(`${id} fg×accent-ui-fill×${bgName}`, theme.foreground, derived.accentUi, TEXT_MIN);
        });

        it(`on-color text ≥ 4.5:1 on ${bgName}`, () => {
          check(
            `${id} primary-fg×primary×${bgName}`,
            derived.primaryForeground,
            theme.primary,
            TEXT_MIN,
          );
          check(
            `${id} secondary-fg×secondary×${bgName}`,
            derived.secondaryForeground,
            derived.secondaryFill,
            TEXT_MIN,
          );
          check(
            `${id} destructive-fg×destructive×${bgName}`,
            derived.destructiveForeground,
            derived.destructive,
            TEXT_MIN,
          );
        });

        it(`UI/focus pairs ≥ 3:1 on ${bgName}`, () => {
          check(`${id} input×${bgName}`, derived.input, bg, UI_MIN);
          check(`${id} accent(focus/ring)×${bgName}`, theme.accent, bg, UI_MIN);
          derived.chart.forEach((chart, i) => {
            check(`${id} chart-${i + 1}×${bgName}`, chart, bg, UI_MIN);
          });
        });
      }
    });
  }
});

describe("imported theme generation", () => {
  const source = fs.readFileSync(path.join(__dirname, "themes.ts"), "utf8");
  const css = fs.readFileSync(path.join(__dirname, "..", "app", "globals.css"), "utf8");
  const imported = THEME_PRESET_IDS.filter((id) => id.startsWith("oc-"));

  it("keeps exactly one generated OpenCode block in each output", () => {
    expect(
      source.match(/OpenCode themes \(imported by scripts\/import-opencode-themes\.mjs\)/g),
    ).toHaveLength(1);
    expect(
      css.match(/OpenCode themes: generated by scripts\/import-opencode-themes\.mjs/g),
    ).toHaveLength(1);
  });

  it("keeps accessible preset labels unique across both groups", () => {
    const labels = THEME_PRESET_IDS.map((id) => themes[id].label);
    expect(new Set(labels).size, "duplicate preset labels make radio names ambiguous").toBe(
      labels.length,
    );
  });

  it("keeps an explicit non-white chart palette for every imported theme", () => {
    for (const id of imported) {
      const chart = themes[id].chart;
      expect(chart, `${id} is missing its generated chart palette`).toBeDefined();
      expect(
        chart?.every((color) => color.toLowerCase() !== "#ffffff"),
        `${id} contains a white chart series`,
      ).toBe(true);
      expect(new Set(chart ?? []).size, `${id} repeats a chart series colour`).toBe(5);
    }
  });
});

describe("chart token wiring", () => {
  const chartSources = [
    "(app)/dashboard/_components/habit-chart.tsx",
    "(app)/focus/_components/focus-chart.tsx",
    "(app)/career/analytics/_components/funnel-chart.tsx",
    "(app)/finance/_components/spend-chart.tsx",
    "(app)/finance/_components/spend-history.tsx",
  ];

  it("keeps series on the chart palette instead of text tokens", () => {
    for (const relative of chartSources) {
      const source = fs.readFileSync(path.join(__dirname, "..", "app", relative), "utf8");
      const colors = [...source.matchAll(/\bcolor:\s*"([^"]+)"/g)].map((match) => match[1]);
      expect(colors.length, `${relative} should declare chart series colours`).toBeGreaterThan(0);
      for (const color of colors) {
        expect(color, `${relative} should use only chart tokens`).toMatch(/^var\(--chart-[1-5]\)$/);
      }
      expect(source, `${relative} should not use text/UI tokens for a series`).not.toMatch(
        /var\(--(?:primary|destructive|success|warning|info)\)/,
      );
    }
  });
});

describe("custom accent chart palette", () => {
  it("keeps every generated series at chart contrast and preserves the danger slot", () => {
    for (const id of ["midnight", "paper", "oc-tokyonight"] as const) {
      const theme = themes[id];
      for (const accent of ["#7aa2f7", "#e0af68", "#ff0055"]) {
        const overrides: ThemeOverrides = {
          ...DEFAULT_THEME,
          preset: id,
          colorMode: id === "paper" ? "light" : "dark",
          accent,
        };
        const vars = accentCssVars(overrides, true);
        for (const surface of [theme.background, theme.card]) {
          for (let index = 1; index <= 5; index += 1) {
            check(
              `${id} accent ${accent} chart-${index}×${surface}`,
              vars[`--chart-${index}`] ?? "",
              surface,
              UI_MIN,
            );
          }
        }
        expect(vars["--chart-4"]).toBe(derivedTokens(theme).chart[3]);
      }
    }
  });
});

describe("derived-token formula parity with globals.css", () => {
  const css = fs.readFileSync(path.join(__dirname, "..", "app", "globals.css"), "utf8");

  it("globals.css uses the same color-mix formulas as derivedTokens()", () => {
    expect(css).toContain("color-mix(in srgb, var(--foreground) 7%");
    expect(css).toContain("color-mix(in srgb, var(--foreground) 8%");
    expect(css).toContain("color-mix(in srgb, var(--foreground) 5%");
    expect(css).toContain("color-mix(in srgb, var(--border) 50%");
    expect(css).toContain("--primary-foreground: var(--background)");
    expect(css).toContain("--ring: var(--accent)");
    expect(css).toContain("--chart-1: var(--primary)");
    expect(css).toContain("--chart-4: var(--destructive)");
    expect(css).toContain("--chart-5: var(--info)");
  });

  it("every preset base block exists in globals.css", () => {
    for (const id of THEME_PRESET_IDS) {
      expect(css, `missing [data-theme=\"${id}\"] block`).toContain(`[data-theme="${id}"]`);
    }
  });
});
